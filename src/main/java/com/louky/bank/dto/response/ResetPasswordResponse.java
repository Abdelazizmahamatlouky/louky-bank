package com.louky.bank.dto.response;

import lombok.Builder;
import lombok.Getter;

/**
 * Reponse de reinitialisation de mot de passe.
 *
 * Le mot de passe temporaire en clair n'est retourne qu'UNE SEULE FOIS
 * au directeur. Il n'est jamais stocke en clair en base : seul son hash
 * BCrypt est conserve dans la colonne `password` existante.
 */
@Getter
@Builder
public class ResetPasswordResponse {

    private final Long userId;
    private final String email;
    private final String temporaryPassword;
    private final boolean autoGenerated;

}